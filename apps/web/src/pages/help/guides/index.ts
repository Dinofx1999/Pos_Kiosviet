const bySlug = new Map(GUIDES.map((g) => [g.slug, g]));
export const getGuide = (slug: string | undefined) => (slug ? bySlug.get(slug) : undefined);
export const getSection = (key: SectionKey) => SECTIONS.find((s) => s.key === key)!;
export const guidesOf = (key: SectionKey) => GUIDES.filter((g) => g.section === key);

/** Screenshot URL for a shot name. Images are generated by `scripts/capture-guide.mjs`. */
export const shotSrc = (shot: string, variant: 'mobile' | 'desktop') => `/guide/${shot}-${variant}.jpg`;

/** Lower-case, accent-insensitive form used for searching ("hoa don" matches "Hóa đơn"). */
export const normalize = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();

const haystack = new Map<string, string>();
const textOf = (g: Guide) => {
  let h = haystack.get(g.slug);
  if (!h) {
    h = normalize([g.title, g.when, getSection(g.section).title, ...(g.keywords ?? []), ...g.perms, ...g.steps.map((s) => `${s.text} ${s.note ?? ''}`), ...(g.notes ?? [])].join(' \n '));
    haystack.set(g.slug, h);
  }
  return h;
};

/** All words of the query must appear somewhere in the guide (title / keywords / steps / notes). Whole-phrase and title hits rank first. */
export function searchGuides(query: string, section?: SectionKey | null): Guide[] {
  const phrase = normalize(query);
  const words = phrase.split(' ').filter(Boolean);
  const pool = section ? GUIDES.filter((g) => g.section === section) : GUIDES;
  if (!words.length) return pool;
  const scored: { g: Guide; score: number }[] = [];
  for (const g of pool) {
    const title = normalize(g.title);
    const body = textOf(g);
    let score = words.length > 1 ? (title.includes(phrase) ? 12 : body.includes(phrase) ? 5 : 0) : 0;
    let ok = true;
    for (const w of words) {
      if (title.includes(w)) score += 3;
      else if (normalize((g.keywords ?? []).join(' ')).includes(w)) score += 2;
      else if (body.includes(w)) score += 1;
      else { ok = false; break; }
    }
    if (ok) scored.push({ g, score });
  }
  return scored.sort((a, b) => b.score - a.score).map((s) => s.g);
}
